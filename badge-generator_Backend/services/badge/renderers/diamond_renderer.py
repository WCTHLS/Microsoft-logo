    def _prep_logo(self, logo):
        """Prepare the Microsoft logo: knock out any white background,
        whiten the gray wordmark, trim to visible bounds, and thicken the
        white wordmark slightly (coloured squares untouched)."""
        import numpy as np
        a = np.array(logo.convert("RGBA")).astype(float)
        rgb = a[:, :, :3]

        # Remove near-white background -> transparent.
        near_white = (rgb.min(2) > 235) & (a[:, :, 3] > 10)
        a[near_white, 3] = 0

        # Whiten the gray wordmark (low saturation), keep coloured squares.
        op = a[:, :, 3] > 10
        mx = rgb.max(2)
        mn = rgb.min(2)
        sat = (mx - mn) / (mx + 1e-6)
        gray = op & (sat < 0.25)
        a[gray, 0] = 255
        a[gray, 1] = 255
        a[gray, 2] = 255

        out = Image.fromarray(a.astype("uint8"), "RGBA")
        bbox = out.getbbox()
        out = out.crop(bbox) if bbox else out

        # Thicken ONLY the white wordmark (squares stay intact).
        #
        # IMPORTANT: this used to threshold alpha into a binary mask,
        # dilate THAT mask, then stamp the newly-covered ring fully
        # opaque. That throws away the source PNG's antialiasing (which
        # lives entirely in partial alpha values -- the RGB is a flat
        # gray/white) and replaces the soft edge with a hard 0->255
        # cliff. At this logo's native resolution (384x82) that hard
        # cliff is only 1px, but once the badge scales the logo up it
        # reads as a visible stair-stepped outline around every letter.
        #
        # Fix: dilate the wordmark's ALPHA VALUES directly (grayscale
        # max filter) instead of a thresholded mask. A pixel just
        # outside the glyph then inherits the (possibly partial) alpha
        # of its nearest wordmark neighbour, so growth still ends in a
        # soft falloff rather than a hard edge.
        arr = np.array(out)
        rgb2 = arr[:, :, :3].astype(float)
        al2 = arr[:, :, 3].astype(float)
        s2 = (rgb2.max(2) - rgb2.min(2)) / (rgb2.max(2) + 1e-6)
        wm = (al2 > 10) & (s2 < 0.25)          # white wordmark pixels only

        wm_alpha_only = np.where(wm, al2, 0).astype("uint8")
        wm_alpha_dilated = np.array(
            Image.fromarray(wm_alpha_only).filter(ImageFilter.MaxFilter(3))
        ).astype(float)

        grown = wm_alpha_dilated > al2
        arr[grown, 0] = 255
        arr[grown, 1] = 255
        arr[grown, 2] = 255
        arr[:, :, 3] = np.maximum(al2, wm_alpha_dilated).astype("uint8")
        out = Image.fromarray(arr, "RGBA")

        return out

    def draw_microsoft_header(self, image, badge):
        logo_dir = Path(__file__).parent.parent / "logo"

        # Prefer the HI-RES logo; _prep_logo strips its white background.
        logo_path = logo_dir / "microsoft_logos.png"
        if not logo_path.exists():
            logo_path = logo_dir / "microsoft_logo.png"
        if not logo_path.exists():
            raise FileNotFoundError(f"Microsoft logo not found: {logo_path}")

        logo = Image.open(logo_path).convert("RGBA")
        logo = self._prep_logo(logo)

        target_w = max(200, int(image.width * self.LOGO_W))
        scale = target_w / logo.width
        target_h = max(1, int(round(logo.height * scale)))
        logo = logo.resize((target_w, target_h), Image.Resampling.LANCZOS)

        start_x = (image.width - logo.width) // 2
        start_y = self._y(image, self.F_LOGO_TOP)
        image.paste(logo, (start_x, start_y), logo)

    def draw_program_category(self, image, text, badge=None):
        if not text:
            return
        draw = ImageDraw.Draw(image)
        colour = self._tinted_colour(
            badge.outer_colour if badge is not None else None,
            self.PROGRAM_TINT,
        )
        target_w = int(image.width * self.W_PROGRAM)
        text_up = text.upper()
        lines = textwrap.wrap(text_up, width=20) or [text_up]
        widest = max(lines, key=len)
        # THINNER (regular) letter-spaced text to match the real badge's
        # tracked all-caps style.
        # NOTE: max_size now comes from PROGRAM_FONT_MAX_FRAC (a canvas-
        # height fraction), not "self.PROGRAM_FONT_SIZE + 30" -- that old
        # ceiling was measured as only producing a ~24px cap-height on a
        # 2048px canvas, well under half the real badge's ~58px. See the
        # PROGRAM_FONT_MAX_FRAC comment above for the full measurement.
        font, tracking = self._fit_tracked_font(
            draw, widest, target_w,
            max_size=int(image.height * self.PROGRAM_FONT_MAX_FRAC), weight="regular",
            tracking_ratio=self.PROGRAM_TRACKING_RATIO,
        )
        self._draw_tracked_block_centered(
            image, lines, self.F_PROGRAM, font, tracking, colour
        )

    def draw_separator(self, image, badge=None):
        draw = ImageDraw.Draw(image)
        center_x = image.width // 2
        y = self._y(image, self.F_SEPARATOR)
        half = int(round(image.width * self.SEPARATOR_HALF_W))
        colour = self._tinted_colour(
            badge.outer_colour if badge is not None else None,
            self.SEPARATOR_TINT,
        )
        draw.line(
            (center_x - half, y, center_x + half, y),
            fill=colour, width=self.SEPARATOR_WIDTH,
        )

    def draw_activity_banner(self, image, text, badge=None):
        if not text:
            return
        draw = ImageDraw.Draw(image)
        # Near-neutral pale gray-blue -- noticeably LESS saturated than
        # the program category text, per the reference badge.
        colour = self._tinted_colour(
            badge.outer_colour if badge is not None else None,
            self.ACTIVITY_TINT,
        )
        target_w = int(image.width * self.W_ACTIVITY)

        # --------------------------------------------------------------
        # Height-aware auto-fit so long / character-heavy activity names
        # shrink to fit instead of overflowing into the title (the old
        # width-only fit let "Frontier Transformation Engineer" spill into
        # "TITAN"), WITHOUT over-shrinking it onto one tiny line.
        #
        # KEY FIX: the block is centred in, and allowed to use the FULL
        # vertical gap between the separator and the title's top edge --
        # NOT a tight symmetric box around F_ACTIVITY. The title sits
        # closer below the old anchor than the separator sits above it, so
        # a symmetric box wasted ~40% of the real room (~150px of ~249px)
        # and forced the text far smaller than necessary. Centring in the
        # gap keeps the spacing to both neighbours consistent on every
        # badge (always vertically centred in that fixed gap) while giving
        # long names enough room to render as two balanced, readable lines.
        # A short name still fits at full size on one line, exactly like
        # the reference badge -- only long/character-heavy names shrink.
        # --------------------------------------------------------------
        title = badge.achievement_name if badge is not None else None
        band_top = self.F_SEPARATOR + self.ACTIVITY_TOP_GAP
        band_bottom = self._title_top_frac(image, title) - self.ACTIVITY_BOTTOM_GAP
        center_frac = (band_top + band_bottom) / 2.0
        max_block_h = max(1, int(round((band_bottom - band_top) * image.height)))

        font, lines = self._fit_wrapped_block(
            draw, text, target_w, max_block_h,
            max_size=self.ACTIVITY_FONT_SIZE + 30, weight="semibold",
            min_size=self.ACTIVITY_MIN_FONT, max_lines=3,
        )
        self._draw_block_centered(image, lines, center_frac, font, colour)

    def draw_main_title(self, image, text):
        if not text:
            return
        draw = ImageDraw.Draw(image)
        text = text.upper()
        target_w = int(image.width * self.W_TITLE)
        # BOLD, but NO extra stroke (so it isn't over-thick).
        font = self._fit_font(
            draw, text, target_w,
            max_size=self.MAIN_TITLE_FONT_SIZE + 30, weight="bold",
        )
        self._draw_block_centered(
            image, [text], self.F_TITLE, font, "white", stroke=0
        )

    def draw_date(self, image, text):
        if not text:
            return
        draw = ImageDraw.Draw(image)
        target_w = int(image.width * self.W_DATE)
        # BOLD, with a touch of tracking so the digits read openly,
        # matching the reference badge's spaced-out date.
        # NOTE: max_size now comes from DATE_FONT_MAX_FRAC (a canvas-
        # height fraction), not "self.DATE_FONT_SIZE + 20" -- that old
        # ceiling was measured as only producing a ~37px cap-height on a
        # 2048px canvas, well under the real badge's ~62px. See the
        # DATE_FONT_MAX_FRAC comment above for the full measurement.
        font, tracking = self._fit_tracked_font(
            draw, str(text), target_w,
            max_size=int(image.height * self.DATE_FONT_MAX_FRAC), weight="bold",
            tracking_ratio=self.DATE_TRACKING_RATIO,
        )
        y_center = image.height * self.F_DATE
        self._draw_tracked_line(image, str(text), y_center, font, tracking, "white")

    # ------------------------------------------------------------------
    def render_badge(self, badge):
        image = self.load_template(badge)
        self.draw_microsoft_header(image, badge)
        self.draw_program_category(image, badge.program_category, badge)
        self.draw_separator(image, badge)
        self.draw_activity_banner(image, badge.activity_track_name, badge)
        self.draw_main_title(image, badge.achievement_name)
        self.draw_date(image, badge.date)
        # Final square sizing is handled in main.py (fit_to_square).
        return image
